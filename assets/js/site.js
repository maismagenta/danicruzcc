  document.querySelectorAll('.phone-showcase').forEach(showcase => {
    const slides = Array.from(showcase.querySelectorAll('.phone-slide'));
    const dots = Array.from(showcase.querySelectorAll('.phone-dots button'));
    if (!slides.length) return;
    const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    let i = 0;
    let timer = null;
    function show(idx) {
      i = (idx + slides.length) % slides.length;
      slides.forEach((s, n) => s.classList.toggle('active', n === i));
      dots.forEach((d, n) => d.setAttribute('aria-current', n === i ? 'true' : 'false'));
    }
    function start() {
      if (prefersReducedMotion || slides.length < 2) return;
      stop();
      timer = setInterval(() => show(i + 1), 3200);
    }
    function stop() {
      if (timer) { clearInterval(timer); timer = null; }
    }
    dots.forEach((d, n) => d.addEventListener('click', () => { show(n); start(); }));
    showcase.addEventListener('mouseenter', stop);
    showcase.addEventListener('mouseleave', start);
    showcase.addEventListener('focusin', stop);
    showcase.addEventListener('focusout', start);
    show(0);
    start();
  });
